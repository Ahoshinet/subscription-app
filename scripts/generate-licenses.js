#!/usr/bin/env node
/**
 * Generates third-party license data for the direct production dependencies.
 *
 *   assets/licenses.json      – bundled into the app (name / version / license / repo)
 *   THIRD_PARTY_LICENSES.md   – full license texts, linked from the app on GitHub
 *
 * Usage: node ./scripts/generate-licenses.js
 */
const fs = require('fs');
const path = require('path');

/* global __dirname */
const ROOT = path.resolve(__dirname, '..');
const rootPkg = require(path.join(ROOT, 'package.json'));
const LICENSE_FILE_RE = /^(licen[cs]e|copying)(\.(md|txt|markdown))?$/i;

function normalizeRepo(repository, homepage) {
  let url = typeof repository === 'string' ? repository : repository?.url;
  if (!url) return homepage ?? null;
  url = url
    .replace(/#.*$/, '')
    .replace(/^git\+/, '')
    .replace(/^git:\/\//, 'https://')
    .replace(/^ssh:\/\/git@/, 'https://')
    .replace(/^git@github\.com:/, 'https://github.com/')
    .replace(/\.git$/, '');
  if (url.startsWith('github:')) url = `https://github.com/${url.slice(7)}`;
  if (/^[\w.-]+\/[\w.-]+$/.test(url)) url = `https://github.com/${url}`;
  if (typeof repository === 'object' && repository?.directory) {
    url = `${url}/tree/HEAD/${repository.directory}`;
  }
  return url;
}

function normalizeLicense(pkg) {
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license?.type) return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type ?? l).join(' OR ');
  return 'UNKNOWN';
}

function readLicenseText(dir) {
  const entries = fs.readdirSync(dir).filter((f) => LICENSE_FILE_RE.test(f));
  if (entries.length === 0) return null;
  return fs.readFileSync(path.join(dir, entries[0]), 'utf8').replace(/\r\n/g, '\n').trim();
}

function anchor(p) {
  return `${p.name}${p.version}`.toLowerCase().replace(/[^a-z0-9-]/g, '');
}

const packages = Object.keys(rootPkg.dependencies ?? {})
  .map((name) => {
    const dir = path.join(ROOT, 'node_modules', name);
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    return {
      name: pkg.name,
      version: pkg.version,
      license: normalizeLicense(pkg),
      repository: normalizeRepo(pkg.repository, pkg.homepage),
      text: readLicenseText(dir),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

fs.writeFileSync(
  path.join(ROOT, 'assets', 'licenses.json'),
  `${JSON.stringify(
    packages.map(({ name, version, license, repository }) => ({ name, version, license, repository })),
    null,
    2,
  )}\n`,
);

const md = [
  '# Third-Party Licenses',
  '',
  'Subscription Manager is built on the open-source packages listed below.',
  'This file is generated by `scripts/generate-licenses.js` — do not edit by hand.',
  '',
  '## Index',
  '',
  ...packages.map((p) => `- [${p.name}@${p.version}](#${anchor(p)}) — ${p.license}`),
  '',
  '## Licenses',
  '',
];
for (const p of packages) {
  md.push(`### ${p.name}@${p.version}`, '');
  md.push(`- License: ${p.license}`);
  if (p.repository) md.push(`- Repository: <${p.repository}>`);
  md.push('');
  if (p.text) {
    md.push('```text', p.text, '```', '');
  } else {
    md.push('_No license file is shipped with this package; see the repository above._', '');
  }
}
fs.writeFileSync(path.join(ROOT, 'THIRD_PARTY_LICENSES.md'), `${md.join('\n')}\n`);

console.log(`Generated ${packages.length} packages.`);
const unknown = packages.filter((p) => p.license === 'UNKNOWN');
if (unknown.length) console.warn(`No license field: ${unknown.map((p) => p.name).join(', ')}`);
const noText = packages.filter((p) => !p.text);
if (noText.length) console.warn(`No license file: ${noText.map((p) => p.name).join(', ')}`);
